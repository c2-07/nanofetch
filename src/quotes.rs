pub fn load_quotes() -> Vec<String> {
    let mut quotes: Vec<String> = BUILTIN_QUOTES.iter().map(|s| s.to_string()).collect();

    // Check for user-defined quotes in ~/.config/nanofetch/quotes.txt
    if let Some(config_dir) = get_config_dir() {
        let custom_file = config_dir.join("quotes.txt");
        if let Ok(content) = fs::read_to_string(&custom_file) {
            for line in content.lines() {
                let trimmed = line.trim();
                if !trimmed.is_empty() && !trimmed.starts_with('#') {
                    quotes.push(trimmed.replace("\\n", "\n"));
                }
            }
        }
    }

    quotes
}

fn get_config_dir() -> Option<PathBuf> {
    if let Ok(xdg) = std::env::var("XDG_CONFIG_HOME") {
        if !xdg.is_empty() {
            return Some(PathBuf::from(xdg).join("nanofetch"));
        }
    }
    if let Ok(home) = std::env::var("HOME") {
        if !home.is_empty() {
            return Some(PathBuf::from(home).join(".config").join("nanofetch"));
        }
    }
    None
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_quotes_exact_365() {
        assert_eq!(BUILTIN_QUOTES.len(), 365);
    }

    #[test]
    fn test_quotes_not_empty() {
        let quotes = load_quotes();
        assert!(quotes.len() >= 365);
        for q in quotes {
            assert!(!q.trim().is_empty());
        }
    }

    #[test]
    fn test_example_quote_present() {
        let quotes = load_quotes();
        let target = "You do not rise to the level of your goals.
You fall to the level of your systems.";
        assert!(quotes.iter().any(|q| q == target));
    }
}
